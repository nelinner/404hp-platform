# ============================================================
#           РЕЗОЛВЕР ID (авто-добавление префикса -100)
# ============================================================
def _resolve_chat_id(x):
    """
    Принимает ID в любом виде:
      17007          → -10017007
      "17007"        → -10017007
      "-1001234567"  → -1001234567
      -1001234567890 → -1001234567890
      -17007         → -17007   (не трогаем, значит уже с минусом)
    """
    if x is None:
        return None
    s = str(x).strip()

    # Уже с -100 — используем как есть
    if s.startswith("-100"):
        return int(s)

    # Отрицательное, но не -100 — оставляем как есть
    if s.startswith("-"):
        return int(s)

    # Положительное — добавляем -100
    return int(f"-100{s}")


